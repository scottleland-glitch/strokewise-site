/* Scopes the app's styles.css under .appui so the app's panels look as they do on the phone inside the coach pages, without touching the coach styles.
 *   NODE_PATH=<dir with postcss> node dev/port/scope-css.js /path/to/app/styles.css > coach/appui.css
 */
const fs = require('fs'), postcss = require('postcss');
const css = fs.readFileSync(process.argv[2] || '/tmp/gst/styles.css', 'utf8'), P = '.appui';
const SKIP_AT = /^(font-face|keyframes|-webkit-keyframes)$/i;
function scope(sel) {
  sel = sel.trim(); if (!sel) return null;
  if (/^(html|body|:root)\b/.test(sel)) {
    // body.hastab / body.noscroll / body.onhome …: state of the phone's page – not used here
    if (/^body\.[\w-]+/.test(sel) && !/^body\.(frostpage)/.test(sel)) return null;
    sel = sel.replace(/^(html\s+)?(body|html|:root)\b\s*/, ''); if (!sel) return P; return P + ' ' + sel;
  }
  sel = sel.replace(/^#app\b/, P);
  if (sel.startsWith(P)) return sel;
  if (sel === '*') return P + ', ' + P + ' *';
  return P + ' ' + sel;
}
const root = postcss.parse(css);
root.walkRules((rule) => {
  const p = rule.parent; if (p && p.type === 'atrule' && SKIP_AT.test(p.name)) return;
  if (p && p.type === 'rule') return;
  const out = []; rule.selectors.forEach((s) => { const x = scope(s); if (x) out.push(x); });
  if (!out.length) { rule.remove(); return; } rule.selectors = out;
});
root.walkAtRules((a) => { if (a.nodes && !a.nodes.length) a.remove(); });
// vars: :root { --x } becomes .appui { --x }; fix relative urls of images the coach pages do not carry
let s = root.toString().replace(/url\((['"]?)img\/[^)'"]*\1\)/g, 'none');
process.stdout.write('/* GENERATED by dev/port/scope-css.js from the StrokeWise app styles.css (v216), scoped under .appui. Do not edit by hand. */\n' + s);
